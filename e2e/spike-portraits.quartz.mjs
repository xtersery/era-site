// Traces the smoky-quartz reference (src/assets/smoky-quartz.png): its silhouette
// per row (left/right edge, 0…1 of the crop box) and a small luminance grid —
// the stone's form and inner density come from the photograph, not from a shape.
import { chromium } from '@playwright/test';
import { readFileSync, writeFileSync } from 'node:fs';
const ROWS = 112, COLS = 56;
const src = 'data:image/png;base64,' + readFileSync('src/assets/smoky-quartz.png').toString('base64');
const b = await chromium.launch({ channel: 'chrome' });
const p = await b.newPage();
const out = await p.evaluate(async ({ src, ROWS, COLS }) => {
  const img = await new Promise((r) => { const i = new Image(); i.onload = () => r(i); i.src = src; });
  const W = img.naturalWidth, H = img.naturalHeight;
  const c = document.createElement('canvas'); c.width = W; c.height = H;
  const g = c.getContext('2d', { willReadFrequently: true });
  g.drawImage(img, 0, 0);
  const d = g.getImageData(0, 0, W, H).data;
  const a = (x, y) => d[(y * W + x) * 4 + 3];
  // the crop box of the opaque pixels
  let x0 = W, x1 = 0, y0 = H, y1 = 0;
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) if (a(x, y) > 128) { x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y); }
  const bw = x1 - x0 + 1, bh = y1 - y0 + 1;
  // per row: the outermost opaque pixels (a row-monotone silhouette keeps the chips)
  const rows = [];
  for (let r = 0; r < ROWS; r++) {
    const y = Math.min(y1, Math.round(y0 + ((r + 0.5) / ROWS) * bh));
    let l = -1, rr = -1;
    for (let x = x0; x <= x1; x++) if (a(x, y) > 128) { if (l < 0) l = x; rr = x; }
    rows.push(l < 0 ? [0.5, 0.5] : [(l - x0) / bw, (rr - x0 + 1) / bw]);
  }
  // a luminance grid inside the box (the smoke: dark = dense)
  const lum = [];
  for (let r = 0; r < ROWS; r++) {
    const y = Math.min(y1, Math.round(y0 + ((r + 0.5) / ROWS) * bh));
    const row = [];
    for (let cc = 0; cc < COLS; cc++) {
      const x = Math.min(x1, Math.round(x0 + ((cc + 0.5) / COLS) * bw));
      const i = (y * W + x) * 4;
      const l = a(x, y) > 128 ? (0.2126 * d[i] + 0.7152 * d[i + 1] + 0.0722 * d[i + 2]) / 255 : -1;
      row.push(Math.round(l * 100) / 100);
    }
    lum.push(row);
  }
  return { box: { x: x0, y: y0, w: bw, h: bh, aspect: bw / bh }, rows, lum };
}, { src, ROWS, COLS });
writeFileSync('spikes/portraits/scene/quartzTrace.ts', `// Generated by e2e/spike-portraits.quartz.mjs from src/assets/smoky-quartz.png — do not edit.\n// The stone's silhouette per row (left/right edge, 0…1 of its crop box) and the smoke's luminance grid.\nexport const trace = ${JSON.stringify(out)} as const;\n`);
console.log('box', out.box, 'rows', out.rows.length, 'sample', out.rows[10], out.rows[56], out.rows[100]);
await b.close();
