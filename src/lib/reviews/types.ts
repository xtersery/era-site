/**
 * A published patient review, as the site shows it — whatever it came from.
 *
 * The shape is the contract between the data layer (`providers.ts`) and the
 * room that shows reviews (`spikes/reviews/`, later `src/sections/Reviews`).
 * The room never knows the provider; the provider never knows the layout.
 */
export type ReviewSource = 'yandex' | '2gis' | 'manual';

export interface Review {
  readonly id: string;
  /** first name and an initial, as the platform shows it — never a full surname we did not get consent for */
  readonly author: string;
  /** 1 … 5 */
  readonly rating: number;
  /** ISO 8601 date (`2026-08-12`) — sorted, then formatted for display */
  readonly date: string;
  readonly text: string;
  readonly source: ReviewSource;
  /** the review's own page on the platform, when there is one */
  readonly sourceUrl?: string;
  /** the platform's avatar, when the platform provides one — never generated by us */
  readonly avatarUrl?: string;
  /** a sample record for the prototype: shown as such, never as a real review */
  readonly isPlaceholder?: boolean;
}

/**
 * Where reviews come from. Every source implements this and nothing else.
 * `sanity` — the CMS, curated by hand; `local` — the prototype's samples.
 */
export interface ReviewsProvider {
  readonly id: ReviewSource | 'sanity' | 'local';
  getReviews(): Promise<readonly Review[]>;
}
